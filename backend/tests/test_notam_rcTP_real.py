"""RCTP 2026-10-16 FAA NOTAM Search 真實內容（E 欄位）。每則都是回歸測試。"""
import pytest

from notam_parser import (CAT_AIRSPACE, CAT_GENERAL, CAT_NAV, CAT_RWY_CLOSED,
                          CAT_TWY, CAT_TWY_CLOSED, CAT_WORK, categorize_notam)


def e(body):  # 包成含 Q 行與 \r\n 的 ICAO 訊息
    return f"A0001/26 NOTAMN\r\nQ) RCAA/QXXXX/IV/M/A/000/999/2505N12114E005\r\nA) RCTP\r\nB) 2608140835 C) PERM\r\nE) {body}"


@pytest.mark.parametrize("body,expected", [
    # --- 真實：之前誤判 / 漏判的 ---
    ("PORTION OF TWY S BTN S4(EXCLUDED) AND S5(EXCLUDED) CLSD DUE TO WIP.", CAT_TWY_CLOSED),
    ("PORTION OF TWY R BTN TWY R1(INCLUDED) AND TWY R3(EXCLUDED)\r\nCLSD FOR ACFT PRKG.", CAT_TWY),
    ("PORTION OF TWY L BEHIND PRKG BAY 525 CLSD FOR ACFT PRKG AND TOWING.\r\nRMK: DEP ACFT IN PRKG BAY 524 PUSH BACK TO TWY L.", CAT_TWY),
    ("PORTION OF TWY E BTN TWY P(EXCLUDED) AND TWY Q(EXCLUDED) ONLY\r\nAVBL FOR ACFT WITH CODE LETTER A, B, C, D, E.", CAT_TWY),
    # --- 真實：空域活動 ---
    ("UNMANNED ACFT WILL BE RELEASED:\r\n1.CASE NR:M260907000101\r\n2.LCA:TAMSUI DISTRICT, NEW TAIPEI CITY\r\n3.THE AREA OVERLAPS TAIPEI FIR", CAT_AIRSPACE),
    ("UNMANNED ACFT WILL BE RELEASED: 1.CASE NR:AB260922001301 2.LCA:DAYUAN DISTRICT, TAOYUAN CITY", CAT_AIRSPACE),
    ("FIREWORKS WILL TAKE PLACE: 1.DOCUMENT NR: 1155023092 2.LCA: DAYUAN DISTRICT, TAOYUAN CITY 3.AIRSPACE BLOCKED.", CAT_AIRSPACE),
    # --- 真實：施工 / 障礙物 ---
    ("AIP SUP 11/26 WEF 01 JUL 2026 TIL 29 SEP 2027, CRANES IN THE VICINITY OF TAIPEI/TAIWAN TAOYUAN INTERNATIONAL AIRPORT.", CAT_WORK),
    ("REF AIP SUP 25/22, TOWER CRANES ARE ERECTED AT TAIPEI/TAIWAN TAOYUAN INTL AP, END DATE REVISED AS 31 JUL 2027.", CAT_WORK),
    ("OBST ERECTED DUE TO NEW GP ANTENNA WIP, INFO AS FLW:\r\n1.COORD: 250344.75N 1211338.96E\r\n2.MAX HGT: 15M AGL", CAT_WORK),
    # --- 真實：一般 ---
    ("AIP SUP 19/26 WEF 03 AUG 2026 TIL 31 DEC 2027, GROUND MANEUVERING RESTRICTIONS FOR AERODROME REFERENCE CODE F AIRCRAFT AT TAIPEI/TAIWAN TAOYUAN INTERNATIONAL AIRPORT.", CAT_GENERAL),
    # --- 邊界案例（設計用） ---
    ("RWY 05L/23R CLSD", CAT_RWY_CLOSED),
    ("RWY 05L AND TWY A CLSD", CAT_RWY_CLOSED),
    ("CRANE ERECTED NEAR RWY 05, TWY A CLSD", CAT_TWY_CLOSED),
    ("TWY A CLSD DUE TO RWY 05 WIP", CAT_TWY_CLOSED),
    ("ILS RWY 05L CLSD", CAT_NAV),
    ("RWY 05L NOT CLSD", "🛫 跑道資訊"),
    ("PORTION OF RWY 05R CLSD", CAT_RWY_CLOSED),
])
def test_real_and_edge_cases(body, expected):
    assert categorize_notam(e(body)) == expected


def test_decimal_numbers_do_not_split_clauses():
    # "250344.75N" 中的小數點不應把子句切開而影響判斷
    assert categorize_notam(e("OBST ERECTED COORD: 250344.75N 1211338.96E, RWY 05L NOT CLSD")) == CAT_WORK
